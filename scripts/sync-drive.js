import { google } from 'googleapis';
import { createWriteStream } from 'fs';
import { mkdir, stat, readdir, unlink } from 'fs/promises';
import { pipeline } from 'stream/promises';
import path from 'path';
import { fileURLToPath } from 'url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const PHOTOS_DIR = path.join(__dirname, '../public/photos');

const IMAGE_MIME_TYPES = new Set([
  'image/jpeg',
  'image/png',
  'image/heic',
  'image/heif',
  'image/gif',
]);

async function listDriveFiles(drive, folderId) {
  const files = [];
  let pageToken;
  do {
    const res = await drive.files.list({
      q: `'${folderId}' in parents and trashed = false`,
      fields: 'nextPageToken, files(id, name, size, mimeType)',
      pageToken,
      pageSize: 1000,
    });
    files.push(...(res.data.files || []).filter(f => IMAGE_MIME_TYPES.has(f.mimeType)));
    pageToken = res.data.nextPageToken;
  } while (pageToken);
  return files;
}

async function downloadFile(drive, fileId, destPath) {
  const res = await drive.files.get({ fileId, alt: 'media' }, { responseType: 'stream' });
  await pipeline(res.data, createWriteStream(destPath));
}

async function main() {
  const credJson = process.env.GOOGLE_SERVICE_ACCOUNT_JSON;
  const folderId = process.env.GOOGLE_DRIVE_FOLDER_ID;

  if (!credJson) { console.error('Missing GOOGLE_SERVICE_ACCOUNT_JSON'); process.exit(1); }
  if (!folderId) { console.error('Missing GOOGLE_DRIVE_FOLDER_ID'); process.exit(1); }

  const auth = new google.auth.GoogleAuth({
    credentials: JSON.parse(credJson),
    scopes: ['https://www.googleapis.com/auth/drive.readonly'],
  });
  const drive = google.drive({ version: 'v3', auth });

  await mkdir(PHOTOS_DIR, { recursive: true });

  const driveFiles = await listDriveFiles(drive, folderId);
  console.log(`Found ${driveFiles.length} image(s) in Drive`);

  const driveFileNames = new Set(driveFiles.map(f => f.name));

  // Download new or changed files
  for (const file of driveFiles) {
    const dest = path.join(PHOTOS_DIR, file.name);
    let needsDownload = true;
    try {
      const s = await stat(dest);
      if (s.size === parseInt(file.size, 10)) needsDownload = false;
    } catch { /* file doesn't exist */ }
    if (needsDownload) {
      console.log(`Downloading: ${file.name}`);
      await downloadFile(drive, file.id, dest);
    }
  }

  // Remove local files no longer in Drive (Drive is source of truth)
  const localFiles = await readdir(PHOTOS_DIR).catch(() => []);
  const localSet = new Set(localFiles);
  for (const name of localFiles) {
    if (name.endsWith('.thumb.webp')) continue; // generated by process.js
    if (driveFileNames.has(name)) continue;

    const ext = path.extname(name).toLowerCase();
    const base = name.slice(0, -ext.length);

    // Skip auto-generated JPGs — handled when we delete their .heic source below
    if ((ext === '.jpg' || ext === '.jpeg') && localSet.has(base + '.heic')) continue;

    await unlink(path.join(PHOTOS_DIR, name));
    console.log(`Removed: ${name}`);

    // Remove the thumbnail generated by process.js
    try {
      await unlink(path.join(PHOTOS_DIR, base + '.thumb.webp'));
      console.log(`Removed (generated): ${base}.thumb.webp`);
    } catch { /* doesn't exist */ }

    // When removing a .heic, also remove the auto-generated .jpg sibling from process.js
    if (ext === '.heic') {
      for (const jpgExt of ['.jpg', '.jpeg']) {
        try {
          await unlink(path.join(PHOTOS_DIR, base + jpgExt));
          console.log(`Removed (generated): ${base}${jpgExt}`);
        } catch { /* doesn't exist */ }
      }
    }
  }
}

main().catch(err => { console.error(err); process.exit(1); });
